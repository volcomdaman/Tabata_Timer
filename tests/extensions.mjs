import assert from 'node:assert/strict';
import { buildSession, DEFAULTS, DEMO, extendPhaseAt, stateAt, sessionCues } from '../timeline.mjs';
import { createWorkoutWav } from '../workout-audio.mjs';
const base=buildSession(DEMO);
const extended=extendPhaseAt(base,4,5);
assert.equal(extended.duration,50);
assert.equal(extended.exercises,base.exercises);
assert.equal(extended.config,base.config);
assert.equal(extended.phases[1].duration,11);
assert.equal(extended.phases[1].start,3);
assert.equal(extended.phases[1].end,14);
assert.equal(extended.phases[0],base.phases[0]);
assert.equal(extended.phases[2].start,14);
assert.equal(extended.phases[2].duration,base.phases[2].duration);
assert.equal(base.duration,45);
assert.equal(base.phases[1].duration,6);
assert.equal(stateAt(extended,9).phase.type,'exercise');
assert.equal(stateAt(extended,14).phase.type,'rest');
const twice=extendPhaseAt(extended,4,5);
assert.equal(twice.duration,55);
assert.equal(twice.phases[1].duration,16);
assert.equal(twice.phases[1].extraSeconds,10);
for(const phase of base.phases.filter(p=>p.type!=='preparation')) {
  const added=extendPhaseAt(base,phase.start+.1,5);
  assert.equal(added.duration,base.duration+5);
  const index=base.phases.indexOf(phase);
  assert.equal(added.phases[index].duration,phase.duration+5);
  assert.equal(added.phases[index].end,phase.end+5);
  added.phases.forEach((p,i)=>{if(i)assert.equal(p.start,added.phases[i-1].end);});
}
let many=base;
for(let i=0;i<1000;i++)many=extendPhaseAt(many,4,5);
assert.equal(many.duration,5045);
assert.equal(many.phases[1].extraSeconds,5000);
assert.equal(many.phases[2].start,5009);
assert.equal(many.config.exercise,6);
assert.throws(()=>extendPhaseAt(base,1),RangeError);
assert.throws(()=>extendPhaseAt(base,45),RangeError);
assert.throws(()=>extendPhaseAt(base,NaN),RangeError);
assert.throws(()=>extendPhaseAt(base,4,0),RangeError);
assert.throws(()=>extendPhaseAt(base,4,-5),RangeError);
const at=4.125;
const wavFull=new DataView(await createWorkoutWav(twice).arrayBuffer());
const wavTail=new DataView(await createWorkoutWav(twice,16000,at).arrayBuffer());
assert.equal(wavTail.getUint32(40,true),Math.round((twice.duration+.85)*16000)*2-Math.round(at*16000)*2);
function sample(view,i){return view.getInt16(44+i*2,true);}
const offset=Math.round(at*16000);
for(let i=0;i<(wavTail.byteLength-44)/2;i++)assert.equal(sample(wavTail,i),sample(wavFull,i+offset),'Rebuilt track must exactly match the future timeline');
const clippedAt=3.1;
const clipped=new DataView(await createWorkoutWav(base,16000,clippedAt).arrayBuffer());
const original=new DataView(await createWorkoutWav(base).arrayBuffer());
for(let i=0;i<800;i++)assert.equal(sample(clipped,i),sample(original,Math.round(clippedAt*16000)+i),'An active tone must retain its envelope and position');
assert.throws(()=>createWorkoutWav(base,16000,46),RangeError);
assert.throws(()=>createWorkoutWav(base,16000,-1),RangeError);
const cues=sessionCues(base);
for(let i=1;i<cues.length;i++)assert.ok(cues[i].time>=cues[i-1].time+cues[i-1].duration-.00001);
const exerciseCue=cues.find(c=>c.time===3);
const restCue=cues.find(c=>c.time===9);
assert.ok(exerciseCue.duration>=.5);
assert.ok(restCue.duration>=.4);
function rms(view,start,seconds){let sum=0;const a=Math.round(start*16000),n=Math.round(seconds*16000);for(let i=0;i<n;i++){const x=sample(view,a+i)/32767;sum+=x*x;}return Math.sqrt(sum/n);}
const newExerciseRms=rms(original,3.05,.3);
const oldRms=.28/Math.sqrt(2);
assert.ok(newExerciseRms>oldRms*3,'Transition must be materially louder than the old beep');
for(let i=0;i<(original.byteLength-44)/2;i++)assert.ok(Math.abs(sample(original,i))<=Math.ceil(.92*32767),'Signal must stay below full scale');
const extraRest=extendPhaseAt(base,10,5);
assert.equal(sessionCues(extraRest).find(c=>c.kind==='finish').time,50);
assert.equal(stateAt(extraRest,12).phase.type,'rest');
const late=extendPhaseAt(base,8.5,5);
assert.deepEqual(sessionCues(late).filter(c=>c.kind==='countdown'&&c.time>=8.5&&c.time<14).map(c=>c.time),[11,12,13]);
console.log(`Passed: repeated +5 s, all rest types, phase boundaries, unchanged presets, exact remaining audio, countdown rescheduling, and ${(20*Math.log10(newExerciseRms/oldRms)).toFixed(1)} dB higher digital RMS without clipping.`);

const roundTripBoundary=base.phases[1].end-1e-12;
assert.equal(stateAt(base,roundTripBoundary).phase.type,'rest');
assert.equal(stateAt(base,roundTripBoundary).phaseRemaining,3);
const boundaryExtension=extendPhaseAt(base,roundTripBoundary,5);
assert.equal(boundaryExtension.phases[1].duration,6);
assert.equal(boundaryExtension.phases[2].duration,8);
assert.equal(stateAt(base,base.duration-1e-12).done,true);
